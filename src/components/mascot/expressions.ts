export type Expression = keyof typeof FACES;
export const EXPRESSION_NAMES = Object.keys(FACES) as Expression[];

// Turn each drawing into a list of true/false (one per pixel), checking the size.
export const EXPRESSIONS = Object.fromEntries(
  Object.entries(FACES).map(([name, rows]) => {
    if (rows.length !== ROWS || rows.some((row) => row.length !== COLS)) {
      throw new Error(`Mascot face "${name}" must be ${COLS}×${ROWS}`);
    }
    return [name, rows.join("").split("").map((ch) => ch === "#")];
  }),
) as Record<Expression, boolean[]>;
